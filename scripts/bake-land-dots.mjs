/**
 * Bake the Path's world: which 1° cells of the globe are land.
 *
 *   node scripts/bake-land-dots.mjs [--src ne_110m_land.geojson]
 *
 * Reads Natural Earth's 1:110m land polygons (public domain; fetched from the
 * project's GitHub when no --src is given) and samples every 1°×1° cell of an
 * equirectangular grid, 360 × 180, at 3×3 points. A cell is land when at least
 * three of the nine fall inside a polygon — so islands the size of a cell
 * survive and a sliver of coast does not.
 *
 * The result is a bitstring, base64, written to src/lib/landDots.ts. The Path's
 * LED globe reads it per diode when it is laid out; nothing is fetched or
 * parsed at runtime.
 *
 * The data is credited in the footer ("Map data: Natural Earth").
 */
import { readFile, writeFile } from "node:fs/promises";

const ROOT = new URL("..", import.meta.url);
const args = process.argv.slice(2);
const src = args.includes("--src") ? args[args.indexOf("--src") + 1] : null;
const URL_110M =
  "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson";

const geo = JSON.parse(src ? await readFile(src, "utf8") : await (await fetch(URL_110M)).text());

/** Every polygon as [outer, ...holes], each ring [[lon, lat], …]. */
const polys = [];
for (const f of geo.features) {
  const g = f.geometry;
  if (g.type === "Polygon") polys.push(g.coordinates);
  else if (g.type === "MultiPolygon") polys.push(...g.coordinates);
}
/* A bounding box per polygon, so most points skip most polygons. */
const boxes = polys.map(([outer]) => {
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (const [x, y] of outer) {
    if (x < x0) x0 = x;
    if (x > x1) x1 = x;
    if (y < y0) y0 = y;
    if (y > y1) y1 = y;
  }
  return [x0, y0, x1, y1];
});

function inRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

function isLand(lon, lat) {
  for (let k = 0; k < polys.length; k++) {
    const [x0, y0, x1, y1] = boxes[k];
    if (lon < x0 || lon > x1 || lat < y0 || lat > y1) continue;
    const [outer, ...holes] = polys[k];
    if (inRing(lon, lat, outer) && !holes.some((h) => inRing(lon, lat, h))) return true;
  }
  return false;
}

const W = 360;
const H = 180;
const bytes = new Uint8Array((W * H) / 8);
let count = 0;
for (let r = 0; r < H; r++) {
  for (let c = 0; c < W; c++) {
    let hits = 0;
    for (let sy = 0; sy < 3; sy++)
      for (let sx = 0; sx < 3; sx++) {
        const lat = 90 - r - (sy + 0.5) / 3;
        const lon = -180 + c + (sx + 0.5) / 3;
        if (isLand(lon, lat)) hits++;
      }
    if (hits >= 3) {
      const i = r * W + c;
      bytes[i >> 3] |= 1 << (i & 7);
      count++;
    }
  }
}

const b64 = Buffer.from(bytes).toString("base64");
const out = `/* Generated by scripts/bake-land-dots.mjs — do not edit. */
/* Land cells of an equirectangular 1° grid, from Natural Earth 1:110m land
   (public domain). Row 0 is 90°N–89°N, column 0 is 180°W–179°W; bit
   (row·${W} + col) of the decoded bytes, least significant bit first. */

export const LAND_W = ${W};
export const LAND_H = ${H};
const LAND_B64 = "${b64}";

let bits: Uint8Array | null = null;

/** Whether the 1° cell holding (lat, lon) is land. Degrees; lon wraps. */
export function isLand(lat: number, lon: number): boolean {
  if (!bits) {
    const raw = atob(LAND_B64);
    bits = new Uint8Array(raw.length);
    for (let i = 0; i < raw.length; i++) bits[i] = raw.charCodeAt(i);
  }
  const r = Math.min(LAND_H - 1, Math.max(0, Math.floor(90 - lat)));
  const c = ((Math.floor(lon + 180) % LAND_W) + LAND_W) % LAND_W;
  const i = r * LAND_W + c;
  return (bits[i >> 3] & (1 << (i & 7))) !== 0;
}
`;
await writeFile(new URL("src/lib/landDots.ts", ROOT), out);
console.log(`landDots: ${count} land cells of ${W * H}, ${b64.length} chars of base64`);
